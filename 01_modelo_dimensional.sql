CREATE DATABASE IF NOT EXISTS dw_vendas
    DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE dw_vendas;

DROP TABLE IF EXISTS f_vendas;
DROP TABLE IF EXISTS d_produto;
DROP TABLE IF EXISTS d_data;

-- ---------------------------------------------------------------------
-- DIMENSAO PRODUTO (script oficial da disciplina)
-- ---------------------------------------------------------------------
CREATE TABLE d_produto (
    id_produto        INTEGER        NOT NULL,
    nome_produto      VARCHAR(100)   NOT NULL,
    categoria_produto VARCHAR(50)    NOT NULL,
    vlr_uni           DECIMAL(10,2)  NOT NULL,
    qtd_estoque       INTEGER        NOT NULL,
    PRIMARY KEY (id_produto)
);

-- ---------------------------------------------------------------------
-- DIMENSAO DATA (calendario)
-- ---------------------------------------------------------------------
CREATE TABLE d_data (
    id_data           INTEGER        NOT NULL,   -- formato AAAAMMDD
    dat_venda         DATE           NOT NULL,
    num_dia           INTEGER        NOT NULL,
    num_mes           INTEGER        NOT NULL,
    nom_mes           VARCHAR(15)    NOT NULL,
    num_trimestre     INTEGER        NOT NULL,
    num_ano           INTEGER        NOT NULL,
    nom_dia_semana    VARCHAR(15)    NOT NULL,
    PRIMARY KEY (id_data)
);

-- ---------------------------------------------------------------------
-- TABELA FATO VENDAS
-- Grao: 1 linha por produto vendido em um dia
-- Metricas aditivas: qtd_vendida e vlr_total
-- ---------------------------------------------------------------------
CREATE TABLE f_vendas (
    id_venda          INTEGER        NOT NULL,
    id_data           INTEGER        NOT NULL,
    id_produto        INTEGER        NOT NULL,
    qtd_vendida       INTEGER        NOT NULL,
    vlr_unitario      DECIMAL(10,2)  NOT NULL,
    vlr_total         DECIMAL(10,2)  NOT NULL,
    PRIMARY KEY (id_venda),
    CONSTRAINT fk_vendas_data    FOREIGN KEY (id_data)    REFERENCES d_data(id_data),
    CONSTRAINT fk_vendas_produto FOREIGN KEY (id_produto) REFERENCES d_produto(id_produto)
);

